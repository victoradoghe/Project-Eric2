export const popularPlaces = (listings) => {
  const counts = new Map();
  listings.forEach((listing) => {
    if (!listing.city || !listing.state) return;
    const key = `${listing.city}|${listing.state}`;
    const entry = counts.get(key) || { city: listing.city, state: listing.state, count: 0 };
    entry.count += 1;
    counts.set(key, entry);
  });
  return [...counts.values()].sort((a, b) => b.count - a.count).slice(0, 8);
};